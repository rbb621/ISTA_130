# False or True
'''
1. Evaluate left side: False.
2. Evaluate right side: True.
3. Since or only needs one side to be True, the result is True.
'''



# True and False
'''
1. Evaluate left side: True.

2. Evaluate right side: False.

With an and statement, both sides must be True. 
As long as one side is false, the whole expression is False.

In plain English: With the and statement, if even one condition is false, 
the whole thing is false.
'''




# not (7 > 3)
'''
1. Evaluate inside the parentheses: 7 > 3 is True.

2. Apply not to the result: not True becomes False.

In plain English: Normally 7 > 3 is True, but not turns the truth value
into False as a result
'''




# not (True or False)
'''
1. Inside the parentheses: True or False will become True, 
because at least one side of or is True.

2. Apply not: not True becomes False.

In plain English: The or would normally be True, 
but the not statement changes it, so the final result is False.
'''




# (not True) and (not False)
'''
1. Evaluate left side: not True becomes False.

2. Evaluate right side: not False becoms True.

3. With and statement, both sides must be true. 
Since one side is false, the result is False.

In plain English: One condition becomes False, the other becomes True, 
so the and statement fails.
'''